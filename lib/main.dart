import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'models.dart';
import 'screens.dart';
import 'services.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const KeihiApp());
}

class KeihiApp extends StatelessWidget {
  const KeihiApp({super.key});

  static Widget _app(Widget home, {Color seed = Colors.teal, ThemeMode mode = ThemeMode.system}) => MaterialApp(
        title: 'Keihi',
        debugShowCheckedModeBanner: false,
        theme: ThemeData(colorSchemeSeed: seed, useMaterial3: true),
        darkTheme: ThemeData(colorSchemeSeed: seed, brightness: Brightness.dark, useMaterial3: true),
        themeMode: mode,
        home: home,
      );

  @override
  Widget build(BuildContext context) => StreamBuilder<User?>(
        stream: FirebaseAuth.instance.authStateChanges(),
        builder: (c, s) {
          if (!s.hasData) return _app(const LoginScreen());
          // Logged in: the user's theme choice comes from their Firestore profile.
          return StreamBuilder<Map<String, dynamic>>(
            stream: Repo.profile(),
            builder: (c, p) => _app(
              const HomeShell(),
              seed: kThemeColors[p.data?['themeColor']] ?? Colors.teal,
              mode: themeModeOf(p.data?['themeMode']),
            ),
          );
        },
      );
}
